# Generates rules/80-net-name-slot.rules, which renames a network interface to the first of its
# candidate names that ifname_valid() of systemd accepts. Every candidate needs the same checks, so the
# rules for one candidate are written once here and repeated for each of them.
#
# It also generates rules/80-net-altnames.rules, which assigns the candidate names as alternative names.
# Both files exist in two variants, for the configure option --with-net-ifnames-default: for yes, the
# default, rules/80-net-name-slot.rules renames the interfaces unless net.ifnames=0 is on the kernel
# command line, and rules/80-net-altnames.rules assigns the alternative names regardless of it; for no,
# the files in rules/net-ifnames-no/ do both only with net.ifnames=1. The build installs one variant.
#
# The build does not run this script; the generated files are kept in git. After changing the script, run
#
#   tools/gen-80-net-name-slot.py [DIRECTORY]
#
# (DIRECTORY defaults to rules/ of the source tree; the files of the variant for no are written to its
# subdirectory net-ifnames-no/) and commit the script and the generated files.

import os
import sys

GENERATED = '''\
# do not edit this file, it will be overwritten on update
# generated by tools/gen-80-net-name-slot.py of the eudev sources, change that script instead
'''

# The check of net.ifnames= on the kernel command line, for --with-net-ifnames-default=yes and no
NET_IFNAMES_CHECK = {
    'yes': '''\
IMPORT{cmdline}="net.ifnames"
ENV{net.ifnames}=="0", GOTO="%(end)s"
''',
    'no': '''\
# eudev was configured with --with-net-ifnames-default=no: only with net.ifnames=1
IMPORT{cmdline}="net.ifnames"
ENV{net.ifnames}!="1", GOTO="%(end)s"
''',
}

HEADER_START = '''\
ACTION!="add", GOTO="net_name_slot_end"
SUBSYSTEM!="net", GOTO="net_name_slot_end"
NAME!="", GOTO="net_name_slot_end"

'''

# after the check of net.ifnames=
HEADER = '''
# like the "keep" and "kernel" policies of systemd, do not rename interfaces named by userspace
# (name_assign_type NET_NAME_USER or NET_NAME_RENAMED), or predictably by the kernel (NET_NAME_PREDICTABLE)
ATTR{name_assign_type}=="2|3|4", GOTO="net_name_slot_end"

# rename the interface to the first valid interface name of these, like ifname_valid() of systemd:
# 1 to 15 characters, not only digits, not ".", "..", "all" or "default", only printable ASCII characters
# other than space, ':', '/' and '%', and not an interface index in another notation of parse_ifindex(),
# i.e. no number from 1 to 2147483647 written as 0x<hex>, +0x<hex>, 0o<octal>, 0o+<octal>, +0<octal>,
# 0b<binary>, 0b+<binary> or +<decimal>; each candidate is copied to .NET_NAME, and .NET_NAME_NUMERIC is set
# if it is such a number
'''

# The candidates, in the order in which they are tried
CANDIDATES = [
    'ID_NET_NAME_FROM_DATABASE',
    'ID_NET_NAME_ONBOARD',
    'ID_NET_NAME_SLOT',
    'ID_NET_NAME_PATH',
    'ID_NET_NAME_MAC',
]

# Set .NET_NAME_NUMERIC if .NET_NAME is a number from 1 to 2147483647 (INT_MAX) in one of the notations
# of parse_ifindex(), i.e. of safe_atoi() of systemd. Glob patterns cannot count, so the upper limit is
# checked by the number of digits after the first significant one, and by the value of that digit when
# the number of digits is the largest possible one. A '-' sign is not checked: such numbers are negative
# or zero, which parse_ifindex() refuses, so they are valid names.
NUMERIC_CHECKS = [
    # hexadecimal: 0x<hex>, +0x<hex>; at most 0x7fffffff
    'ENV{.NET_NAME}=="0[xX]?*|+0[xX]?*", ENV{.NET_NAME}!="*[xX]*[!0-9a-fA-F]*", ENV{.NET_NAME}=="*[xX]*[1-9a-fA-F]*", \\\n'
    '  ENV{.NET_NAME}!="*[1-9a-fA-F]????????*|*[89a-fA-F]???????", ENV{.NET_NAME_NUMERIC}="1"',
    # decimal: +<decimal>; at most +2147483647
    'ENV{.NET_NAME}=="+[1-9]*", ENV{.NET_NAME}!="+*[!0-9]*", \\\n'
    '  ENV{.NET_NAME}!="+???????????*|+[3-9]?????????|+2[2-9]????????|+21[5-9]???????|+214[89]??????|'
    '+2147[5-9]?????|+21474[9]????|+214748[4-9]???|+2147483[7-9]??|+21474836[5-9]?|+214748364[89]", \\\n'
    '  ENV{.NET_NAME_NUMERIC}="1"',
    # octal: 0o<octal>, 0o+<octal>, +0<octal>; at most 017777777777
    'ENV{.NET_NAME}=="0[oO][+0-7]*|+0?*", ENV{.NET_NAME}!="0[oO]?*[!0-7]*|+?*[!0-7]*", ENV{.NET_NAME}=="*[1-7]*", \\\n'
    '  ENV{.NET_NAME}!="*[1-7]???????????*|*[2-7]??????????", ENV{.NET_NAME_NUMERIC}="1"',
    # binary: 0b<binary>, 0b+<binary>; a valid name has at most 15 characters, too few to exceed the limit
    'ENV{.NET_NAME}=="0[bB][+01]*", ENV{.NET_NAME}!="0[bB]?*[!01]*", ENV{.NET_NAME}=="*1*", ENV{.NET_NAME_NUMERIC}="1"',
]

# The other checks of ifname_valid(), and the rename
VALID = ('ENV{.NET_NAME_NUMERIC}!="1", ENV{.NET_NAME}=="*[!0-9]*", '
         'ENV{.NET_NAME}!="????????????????*|.|..|all|default|*[!!-~]*|*[:/%]*", ')

# The name that net_id generates for an all-zero MAC address, which is not used
MAC_EXTRA = 'ENV{.NET_NAME}!="??x000000000000", '


# 80-net-altnames.rules; for --with-net-ifnames-default=yes, the alternative names do not depend on
# net.ifnames=
ALTNAMES = '''\

# Assign the predictable names of network interfaces, the ID_NET_NAME_* properties of the net_id
# builtin (see 75-net-description.rules), as alternative names, like the default
# AlternativeNamesPolicy= of systemd, also to interfaces that are not renamed; not the name the
# interface gets. Disabled by net_altnames=no in udev.conf.

ACTION!="add", GOTO="net_altnames_end"
SUBSYSTEM!="net", GOTO="net_altnames_end"
%(check)s
OPTIONS+="net_altnames"

LABEL="net_altnames_end"
'''


def generate_altnames(net_ifnames_default):
    check = ''
    if net_ifnames_default == 'no':
        check = '\n' + NET_IFNAMES_CHECK['no'] % {'end': 'net_altnames_end'}
    return GENERATED + ALTNAMES % {'check': check}


def generate(net_ifnames_default):
    out = [GENERATED, '\n', HEADER_START, NET_IFNAMES_CHECK[net_ifnames_default] % {'end': 'net_name_slot_end'}, HEADER]
    for candidate in CANDIDATES:
        out.append('\n')
        out.append('ENV{.NET_NAME}="$env{%s}", ENV{.NET_NAME_NUMERIC}=""\n' % candidate)
        for check in NUMERIC_CHECKS:
            out.append(check + '\n')
        extra = MAC_EXTRA if candidate == 'ID_NET_NAME_MAC' else ''
        out.append(VALID + '\\\n  ' + extra + 'NAME="$env{.NET_NAME}", GOTO="net_name_slot_end"\n')
    out.append('\nLABEL="net_name_slot_end"\n')
    return ''.join(out)


def write(path, text):
    with open(path, 'w', encoding='ascii') as f:
        f.write(text)


def main():
    if len(sys.argv) > 2:
        sys.exit('usage: %s [DIRECTORY]' % sys.argv[0])
    if len(sys.argv) == 2:
        directory = sys.argv[1]
    else:
        directory = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rules')
    for net_ifnames_default, subdir in (('yes', ''), ('no', 'net-ifnames-no')):
        d = os.path.join(directory, subdir)
        os.makedirs(d, exist_ok=True)
        write(os.path.join(d, '80-net-name-slot.rules'), generate(net_ifnames_default))
        write(os.path.join(d, '80-net-altnames.rules'), generate_altnames(net_ifnames_default))


if __name__ == '__main__':
    main()
