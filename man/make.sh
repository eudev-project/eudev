#!/bin/sh

set -e

XSLTPROC="/usr/bin/xsltproc"

XSLTPROC_FLAGS="--nonet \
--xinclude \
--maxdepth 9000 \
--stringparam man.output.quietly 1 \
--stringparam funcsynopsis.style ansi \
--stringparam man.th.extra1.suppress 1 \
--stringparam man.authors.section.enabled 0 \
--stringparam man.copyright.section.enabled 0"

# The text that depends on the configure option --with-net-ifnames-default is marked with
# <phrase condition="net-ifnames-yes"> and <phrase condition="net-ifnames-no">. The man pages are made for
# yes, the default. For a page with such text, make.sh also writes net-ifnames-no/<page>.sed, which turns
# the page into the one for no, and which the build runs when eudev is configured with
# --with-net-ifnames-default=no: the lines that differ, from diff, replaced by their line numbers.
xslt_proc() {
	[ "$V" = 1 ] && echo $XSLTPROC -o $1.$2 $XSLTPROC_FLAGS --stringparam profile.condition net-ifnames-yes custom-man.xsl $1.xml
	$XSLTPROC -o $1.$2 $XSLTPROC_FLAGS --stringparam profile.condition net-ifnames-yes custom-man.xsl $1.xml
}

net_ifnames_no() {
	# the page for no, in a directory of its own, as the style sheet names the files after the pages
	rm -rf net-ifnames-no.tmp
	mkdir net-ifnames-no.tmp
	(cd net-ifnames-no.tmp && $XSLTPROC $XSLTPROC_FLAGS --stringparam profile.condition net-ifnames-no ../custom-man.xsl ../$1.xml)
	diff $1.$2 net-ifnames-no.tmp/$1.$2 > net-ifnames-no.tmp/diff || [ $? = 1 ]
	# the build checks the cksum of the page, so that it never edits a page that changed without make.sh
	{
		echo "# generated by man/make.sh from man/$1.xml: turns $1.$2 into the page for --with-net-ifnames-default=no"
		echo "# made for $1.$2 with the cksum `cksum < $1.$2`"
		# the commands of diff become the sed commands c, a and d for the same lines; in the text of c and
		# a, a backslash is doubled, a leading blank kept with a backslash, and the lines but the last end
		# with a backslash
		awk '
			function flush() { if (pending != "") print pending; pending = "" }
			/^[0-9]+(,[0-9]+)?[acd][0-9]+(,[0-9]+)?$/ {
				flush()
				match($0, /[acd]/)
				c = substr($0, RSTART, 1)
				if (c == "d")
					print substr($0, 1, RSTART - 1) "d"
				else
					print substr($0, 1, RSTART - 1) c "\\"
				next
			}
			/^> / {
				t = substr($0, 3)
				gsub(/\\/, "&&", t)
				if (t ~ /^[ \t]/)
					t = "\\" t
				if (pending != "")
					print pending "\\"
				pending = t
				next
			}
			/^< / || /^---$/ { next }
			{ bad = 1; exit 1 }
			END { if (!bad) flush() }
		' net-ifnames-no.tmp/diff
	} > net-ifnames-no/$1.$2.sed
	sed -f net-ifnames-no/$1.$2.sed $1.$2 | cmp -s - net-ifnames-no.tmp/$1.$2 ||
		{ echo "net-ifnames-no/$1.$2.sed does not make the page for --with-net-ifnames-default=no" >&2; exit 1; }
	rm -rf net-ifnames-no.tmp
}

xslt_proc udev 7
xslt_proc hwdb 7
xslt_proc systemd-hwdb 8
xslt_proc udev.conf 5
xslt_proc udevd 8
xslt_proc udevadm 8

mkdir -p net-ifnames-no
net_ifnames_no udev 7
net_ifnames_no udev.conf 5
net_ifnames_no udevd 8
